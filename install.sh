#!/usr/bin/env bash
#
# Harbour Mooring Waitlist Board - one-command setup.
#
# Installs the project's own dependencies, builds the compiled single-page app,
# creates the SQLite schema and seeds the demo harbour. It NEVER starts a server
# and never installs a system package: everything below is a project-level
# command run as an ordinary user.
set -euo pipefail

cd "$(dirname "$0")"

echo "==> Harbour Mooring Waitlist Board - setup"

# Some distributions mark the system interpreter as externally managed (PEP 668).
# This only unblocks pip for the project's own requirements; nothing is installed
# system-wide beyond those packages.
export PIP_BREAK_SYSTEM_PACKAGES=1

if ! command -v python3 >/dev/null 2>&1; then
  echo "ERROR: python3 is required (see INSTALL.md for prerequisites)." >&2
  exit 1
fi

if ! command -v npm >/dev/null 2>&1; then
  echo "ERROR: npm is required (see INSTALL.md for prerequisites)." >&2
  exit 1
fi

echo "==> Python dependencies (backend/requirements.txt)"
pip3 install --quiet --upgrade pip setuptools wheel
pip3 install --quiet -r backend/requirements.txt

echo "==> Front-end dependencies (frontend/package.json)"
npm --prefix frontend install --no-audit --no-fund

echo "==> Building the single-page app (npm run build)"
npm --prefix frontend run build

if [ ! -f .env ]; then
  echo "==> Writing .env with a freshly generated session secret"
  session_secret="$(python3 -c 'import secrets; print(secrets.token_hex(32))')"
  {
    echo "# Generated by install.sh. Local development values only."
    echo "SESSION_SECRET=${session_secret}"
    echo "DATABASE_URL=sqlite:///./harbour.db"
    echo "SEED_ON_START=true"
    echo "DEBUG=false"
    echo ""
  } > .env
fi

echo "==> Creating the schema and seeding the demo harbour"
(cd backend && python3 -m seed)

echo "==> Verifying the API package imports cleanly"
(cd backend && python3 -c "import main; assert main.app is not None")

echo
echo "Setup complete."
echo "Start the app with:  bash start.sh"
echo "Demo sign-in:        cenius@cenius.ai / cenius"
